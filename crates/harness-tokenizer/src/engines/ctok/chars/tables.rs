/// Whether `ch` lies in one of the inclusive `ranges`, which need not be sorted.
pub(super) fn in_ranges(ranges: &[(u32, u32)], ch: char) -> bool {
    let cp = u32::from(ch);
    ranges.iter().any(|&(lo, hi)| lo <= cp && cp <= hi)
}
